# 2026-11-03（第 67 期）写回 tracking.json，只追加不删除
import json, shutil, datetime

P = "/workspace/site/history/tracking.json"
shutil.copy(P, P + ".bak_1103")
d = json.load(open(P, encoding="utf-8"))
topics = d["topics"]
DATE = "2026-11-03"

def find(key):
    for i, t in enumerate(topics):
        if key in t["topic"]:
            return i, t
    return None, None

def add_region(key, region, detail, date=DATE):
    i, t = find(key)
    assert t is not None, key
    for r in t["regions"]:
        if isinstance(r, str):
            continue
        if r.get("region") == region:
            r["detail"] = detail
            r["date"] = date
            return
    t["regions"].append({"region": region, "date": date, "detail": detail})
    return

def add_change(key, change, date=DATE):
    i, t = find(key)
    assert t is not None, key
    for c in t["changes"]:
        if isinstance(c, dict) and c.get("date") == date:
            c["change"] = change
            return
    t["changes"].append({"date": date, "change": change})

def new_topic(topic, first_region, detail, change):
    topics.append({"topic": topic, "first_seen": DATE, "first_region": first_region,
                   "regions": [{"region": first_region, "date": DATE, "detail": detail}],
                   "changes": [{"date": DATE, "change": change}]})

