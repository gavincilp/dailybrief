# -*- coding: utf-8 -*-
import json

path = 'history/tracking.json'
with open(path, 'r', encoding='utf-8') as f:
    data = json.load(f)

topics = data['topics']

def find(t):
    for x in topics:
        if x['topic'] == t:
            return x
    return None

def append_region(t, region, date, detail):
    x = find(t)
    if x is None:
        return False
    for r in x.get('regions', []):
        if r['region'] == region and r.get('date') == date:
            return True
    x.setdefault('regions', []).append({'region': region, 'date': date, 'detail': detail})
    return True

def append_change(t, date, change):
    x = find(t)
    if x is None:
        return False
    x.setdefault('changes', []).append({'date': date, 'change': change})
    return True

